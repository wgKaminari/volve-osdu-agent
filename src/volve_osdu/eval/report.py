def write_report(
    path: Path,
    results: list,
    summaries: dict[str, dict[str, Any]],
    bundles: list[Bundle],
    meta: dict[str, str],
) -> None:
    names = [r.name for r in results]
    write_json(path.with_suffix(".json"), results, summaries, meta)
    labels = list(csv.DictReader((m.GOLD / "curve_labels.csv").open()))
    reviewed = sum(r["reviewed"] == "true" for r in labels)
    gold = m.load_header_gold()
    annotations_reviewed = sum(r["annotations_reviewed"] == "True" for r in gold.values())
    conflicts = load_conflicts()

    lines = [
        "# Evaluation results",
        "",
        f"Generated by `uv run volve-osdu eval` on {meta['date']} at commit `{meta['commit']}`.",
        "Do not edit by hand; re-run the command.",
        "",
        f"n = {len(bundles)} wellbores (header gold for 11). 95% CIs: wellbore bootstrap, "
        f"{m.BOOTSTRAP_RESAMPLES} resamples. Flag precision/recall also use "
        f"{len({c.bundle for c in conflicts})} bundles with known or injected conflicts.",
        "",
        "> **Gold review status.** Curve labels: "
        f"{reviewed}/{len(labels)} rows reviewed by the owner. Disputed/recoverable annotations on "
        f"the NPD header gold: {annotations_reviewed}/{len(gold)} reviewed. Numbers that rest on "
        "unreviewed labels are provisional.",
        "",
        "## Summary",
        "",
        "| Metric | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    rows = [
        ("Field accuracy (recoverable, undisputed)", "field_accuracy"),
        ("Abstention accuracy (value not in inputs)", "abstention_accuracy"),
        ("Report-prose facts (KB, TD, KOP)", "report_fact_accuracy"),
        ("Curve unit accuracy (unreviewed labels)", "curve_unit_accuracy"),
        ("Curve family accuracy (unreviewed labels)", "curve_family_accuracy"),
        ("Grounding: report facts kept / proposed", "grounding_final"),
        ("Grounding on the first attempt", "grounding_first_attempt"),
        ("Hallucination rate (value in no input)", "hallucination_rate"),
        ("Validation pass rate (wellbores)", "validation_pass_rate"),
        ("Review-flag precision", "flag_precision"),
        ("Review-flag recall", "flag_recall"),
    ]
    for label, key in rows:
        lines.append(f"| {label} | " + " | ".join(summaries[n][key].fmt() for n in names) + " |")

    lines += [
        "",
        "## Read this first (caveats)",
        "",
        "- **No held-out set.** The rules regexes and curve dictionary were written after "
        "reading these same 13 bundles, so its scores are optimistic (fit to the test set). The "
        "agent's prompts are generic and were not tuned per wellbore.",
        "- **Curve labels are not independent of the rules dictionary**: both were drafted by the "
        "same author with the same unit conventions, so rules curve-unit accuracy is near 100% by "
        "construction. The LLM systems' curve numbers, after owner review, are the real signal.",
        "- **Small n.** 13 wellbores, header gold for 11; some per-field rows have 1-7 values. The "
        "confidence intervals are wide on purpose.",
        "- **Disputed gold is excluded from accuracy** and listed below with each system's value; "
        "gold is never edited to match a system.",
        "- **Local small model.** LLM numbers come from the model and settings in Run "
        "configuration; a stronger hosted model only needs a different `.env`.",
    ]
    lines += [
        "",
        "## Changes made after looking at results (all reported)",
        "",
        "- **Agent run 1** ([results_agent_run1.md](results_agent_run1.md)) showed facts that "
        "were quoted verbatim but were the wrong kind of fact or the wrong wellbore (TD 347 m "
        "taken as KB elevation; the kick-off point of 15/9-F-11 T2 given to 15/9-F-11). Rule 8 "
        "gained generic semantic checks: fact keyword in the quote, plausible range, wellbore "
        "attribution. Prompts were not changed. Compare the two reports for the effect.",
        "- **Agent identity fallback:** when the model abstains on the wellbore name, the most "
        "specific header name is used and flagged (`identity_fallback`) instead of building "
        "nothing.",
        "- **llm_only parser:** made lenient (keep valid items, drop malformed ones), so the "
        "baseline is judged on its answers, not on a strict parser that discarded whole replies.",
    ]
    lines += [
        "",
        "## Per-field accuracy",
        "",
        "| Fact | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for fact in m.SCORED_FACTS:
        lines.append(
            f"| {fact} | " + " | ".join(summaries[n]["per_fact"][fact].fmt() for n in names) + " |"
        )
    lines.append(
        "| operator (strict, exact name) | "
        + " | ".join(summaries[n]["operator_strict"].fmt() for n in names)
        + " |"
    )
    lines += [
        "",
        "Operator is scored with a documented alias list (Statoil, StatoilHydro, Den norske "
        "stats oljeselskap and Equinor are one company, `eval/gold.py`); the strict row needs "
        "the exact NPD name.",
    ]

    lines += [
        "",
        "## Disputed gold (inputs disagree with NPD; reported, not scored)",
        "",
        "| Wellbore | Fact | NPD | " + " | ".join(names) + " | Why |",
        "|---|---|---|" + "---|" * len(names) + "---|",
    ]
    disputed = [o for o in results[0].outcomes if o.kind == "disputed"]
    for row in disputed:
        values = []
        for r in results:
            match = next(
                o
                for o in r.outcomes
                if (o.wellbore, o.fact, o.kind) == (row.wellbore, row.fact, "disputed")
            )
            values.append(_v(match.predicted))
        lines.append(
            f"| {row.wellbore} | {row.fact} | {row.gold} | "
            + " | ".join(values)
            + f" | {row.note} |"
        )

    lines += ["", "## Errors", ""]
    for r in results:
        wrong = [o for o in r.outcomes if o.kind in ("field", "abstain") and o.correct is False]
        lines += [f"### {r.name}: {len(wrong)} wrong header values", ""]
        if wrong:
            lines += ["| Wellbore | Fact | Gold | Emitted | Note |", "|---|---|---|---|---|"]
            for o in wrong[:15]:
                note = "should abstain: " + o.note if o.kind == "abstain" else _evidence(r, o)
                lines.append(
                    f"| {o.wellbore} | {o.fact} | {o.gold or '(null)'} "
                    f"| {_v(o.predicted)} | {note} |"
                )
            lines.append("")
        s = summaries[r.name]
        if s["false_flags"]:
            lines.append(
                "False review flags: " + "; ".join(f"{b} {f} {x}" for b, f, x in s["false_flags"])
            )
        if s["missed_conflicts"]:
            lines.append(
                "Missed conflicts: "
                + "; ".join(f"{b} {f} {x}" for b, f, x in s["missed_conflicts"])
            )
        lines.append("")

    lines += [
        "## Cost and latency (real bundles)",
        "",
        "| System | Model | LLM calls/wellbore | Tokens/wellbore | Seconds/wellbore "
        "| Wellbores needing retries | API calls this run |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        llm = summaries[r.name]["llm"]
        lines.append(
            f"| {r.name} | {r.model or '-'} | {llm['calls_per_wellbore']:.1f} | "
            f"{llm['tokens_per_wellbore']:.0f} | {llm['seconds_per_wellbore']:.0f} | "
            f"{llm['retries']} | {llm['api_calls_this_run']} |"
        )
    lines += [
        "",
        "Seconds = model time per wellbore when each call was first made (from the cache "
        "records), on a laptop RTX 3050 Ti (4 GB). Re-runs from cache take no model time.",
        "",
    ]

    prompts = sorted(
        {t["prompt_version"] for r in results for p in r.real.values() for t in p.trace}
    )
    lines += [
        "## Run configuration",
        "",
        f"- Systems: {', '.join(names)}",
        f"- Models: {', '.join(sorted({r.model for r in results if r.model})) or '-'}",
        f"- LLM endpoint: `{os.environ.get('LLM_BASE_URL', '-')}`, reasoning effort "
        f"`{os.environ.get('LLM_REASONING_EFFORT') or 'default'}`, temperature 0",
        f"- Prompt versions: {', '.join(prompts) or '-'}",
        "- Data pins: " + ", ".join(f"{k} {v}" for k, v in PINS.items()),
        f"- Perturbations: {len(PERTURBATIONS)} "
        "(`src/volve_osdu/eval/perturb.py`), conflicts in `data/gold/conflicts.csv`",
        "",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_json(
    path: Path, results: list, summaries: dict[str, dict[str, Any]], meta: dict[str, str]
) -> None:
    """Machine-readable results (docs/results.json) for the HTML report and anyone re-using them."""

    def plain(value: Any) -> Any:
        if isinstance(value, Estimate):
            return asdict(value)
        if isinstance(value, dict):
            return {k: plain(v) for k, v in value.items()}
        if isinstance(value, list | tuple):
            return [plain(v) for v in value]
        return value

    doc = {
        "meta": meta,
        "systems": {
            r.name: {
                "model": r.model,
                "summary": plain(summaries[r.name]),
                "outcomes": [asdict(o) for o in r.outcomes if not o.kind.startswith("curve")],
            }
            for r in results
        },
    }
    path.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def _v(value: object) -> str:
    return "(null)" if value is None else str(value)


def _evidence(result: Any, outcome: m.Outcome) -> str:
    pred = next(p for name, p in result.real.items() if name == outcome.wellbore)
    fact_key = {
        "latitude": "surface_latitude_deg",
        "longitude": "surface_longitude_deg",
        "operator": "operator_name",
        "field": "field_name",
    }.get(outcome.fact, outcome.fact)
    fact = pred.facts.get(fact_key, {})
    sources = fact.get("provenance", [])
    if not sources:
        return "no source recorded" if outcome.predicted is not None else "abstained"
    p = sources[0]
    quote = f' "{p["quote"][:90]}"' if p.get("quote") else ""
    return f"{p['source_file'].rsplit('/', 1)[-1]} {p['locator']}{quote}"


